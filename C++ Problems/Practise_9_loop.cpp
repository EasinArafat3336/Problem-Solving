

#include <iostream>
using namespace std;

int main(){

  //store
  int i, n , sum = 0;

  //input
  cout << "Enter a number : ";
  cin >> n;

  //loop
  for (int i = 11; i <= n; i++)
  {
    cout << i << " ";
    sum = sum + i;
  }
  cout << sum;

  //this code can calculate sum of n"th numbers. 












  return 0;
}